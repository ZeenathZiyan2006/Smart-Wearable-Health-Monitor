from datetime import datetime
from typing import List, Optional
from pydantic import BaseModel, Field


class ECGSignalSample(BaseModel):
    timestamp_ms: int = Field(..., description="Sample timestamp in relative milliseconds")
    amplitude_mv: float = Field(..., description="ECG amplitude in millivolts")


class ECGIngestRequest(BaseModel):
    device_uuid: str = Field(..., description="Hardware identifier of the wearable ECG sensor")
    sampling_rate_hz: int = Field(250, description="Sampling rate in Hz (e.g. 125, 250, 500)")
    lead: str = Field("Lead I", description="ECG Lead orientation, e.g. Lead I, Lead II")
    samples: List[float] = Field(..., min_length=1, max_length=5000, description="Raw ECG ADC values or mV readings")
    is_simulated: bool = Field(False, description="Flag indicating if signal was generated by test harness or real sensor")


class ECGIngestResponse(BaseModel):
    status: str
    samples_received: int
    sampling_rate_hz: int
    duration_seconds: float
    estimated_heart_rate: Optional[int] = None
    rhythm_interpretation: str
    is_simulated: bool
    disclaimer: str


class GeofenceCheckRequest(BaseModel):
    latitude: float
    longitude: float
    center_latitude: float = 12.9716
    center_longitude: float = 77.5946
    radius_meters: float = 500.0


class GeofenceCheckResponse(BaseModel):
    is_inside: bool
    distance_from_center_meters: float
    safe_zone_radius_meters: float
    alert_triggered: bool
    message: str
